"""Spatial-cue props for the convenience / grocery sales floor (S13 review 10-19: ref data/venue_refs/shopL_grocery_ref/ref1.jpg). Factory-shaped (Cls(seed).spawn_asset(i), front +X, back at x = 0).

  CoolerWallFactory     a continuous wall of glass-door coolers: 6 or 8 doors (0.64 m each), white frame, tinted glass doors with chrome handles, lit interior, 5 shelves of bottles / cartons per door,
                        and category sign boards (DAIRY / FOOD / SNACKS / BEVERAGE ...) above the doors; 0.75 m deep, 2.55 m high with the signs
  PegboardEndcapFactory a gondola end cap (0.5 x 0.9 x 1.7 m): white pegboard with hook rows of blister packs on coloured cards
  CategorySignFactory   one hanging / wall sign board (0.04 x 1.2 x 0.3 m, origin at the bottom) with a category word
Sign images: data/venue_refs/prop_textures/catsign_<word>.png (generated by PIL, crisp).
"""
from __future__ import annotations

import random

from room_planner import proc_assets as pa

SIGN_WORDS = ("dairy", "food", "snacks", "beverage", "frozen", "fresh", "health", "household")
DRINK = ((0.12, 0.35, 0.8), (0.1, 0.6, 0.35), (0.85, 0.15, 0.12), (0.95, 0.95, 0.9), (0.9, 0.7, 0.1), (0.55, 0.3, 0.12), (0.4, 0.75, 0.9))


def _sign_mat(word):
    p = pa.PRINT_ROOT / f"catsign_{word}.png"
    return pa._printed(p, (0.9, 0.9, 0.9), 0.5) if p.exists() else pa._flat(f"ir_catsign_{word}", (0.5, 0.5, 0.5), 0.5)


class CoolerWallFactory:
    def __init__(self, seed):
        self.r = random.Random(seed); self.n = self.r.choice(tuple(pa.STYLE.get("cooler_doors") or (6, 8)))                      # kit cooler_doors=[7, 8]: a longer, continuous run (S37 r2: the cooler wall stayed short)

    def spawn_asset(self, i):
        r, n = self.r, self.n
        W, D, H = 0.64, 0.75, 2.05
        L = n * W
        cf_ = pa.STYLE.get("cooler_frame_rgb")                                          # kit cooler_frame_rgb: black cabinet + door frames (the ref coolers)
        white = pa._flat("ir_cooler_white", (0.9, 0.9, 0.9), 0.35, 0.2) if not cf_ else pa._flat(f"ir_cooler_frame_{int(cf_[0] * 100)}", tuple(cf_), 0.4, 0.3); chrome = pa._flat("ir_cooler_chrome", (0.8, 0.8, 0.82), 0.25, 1.0)
        glass = pa._flat("ir_cooler_glass", (0.35, 0.4, 0.42) if not pa.STYLE.get("cooler_glow") else (0.8, 0.85, 0.88), 0.04, transmission=0.85)
        glow = pa._flat("ir_cooler_glow", (0.95, 0.97, 1.0), 0.4); gb = glow.node_tree.nodes["Principled BSDF"]
        gb.inputs["Emission Color"].default_value = (0.9, 0.95, 1.0, 1); gb.inputs["Emission Strength"].default_value = float(pa.STYLE.get("cooler_glow") or 3.5)                    # kit cooler_glow: a brighter lit interior
        frame = [(-D / 2 + 0.02, 0, H / 2, 0.04, L, H, (0, 0, 0)), (0, 0, 0.07, D, L, 0.14, (0, 0, 0)), (0, 0, H - 0.1, D, L, 0.2, (0, 0, 0))]
        frame = [("box", (a, b, c), (d, e, f), rot) for a, b, c, d, e, f, rot in frame]
        gl, ch, gw, shelves = [], [], [], []
        for k in range(n + 1):
            y = -L / 2 + k * W
            frame.append(("box", (0.0, y, H / 2), (D, 0.03, H), (0, 0, 0)))
        for k in range(n):
            yc = -L / 2 + (k + 0.5) * W
            gl.append(("box", (D / 2 - 0.02, yc, H / 2), (0.02, W - 0.05, H - 0.3), (0, 0, 0)))
            ch.append(("cyl", (D / 2 + 0.03, yc + W / 2 - 0.07, H / 2), (0.012, 0.012, 0.6), (0, 0, 0)))
            gw.append(("box", (-D / 2 + 0.05, yc, H / 2), (0.01, W - 0.06, H - 0.35), (0, 0, 0)))
        bottles = {}
        BRIGHT = [(0.95, 0.5, 0.1), (0.5, 0.8, 0.2), (0.2, 0.55, 0.9), (0.96, 0.96, 0.95), (0.95, 0.35, 0.45), (0.98, 0.85, 0.2), (0.85, 0.15, 0.15), (0.3, 0.75, 0.7)]
        kinds = ["bottle", "can", "carton", "juice", "bottle", "can"]
        r.shuffle(kinds)
        for k in range(n):
            yc = -L / 2 + (k + 0.5) * W
            col = r.choice(DRINK); col2 = r.choice(DRINK)
            for sh in range(5):
                z = 0.28 + sh * 0.33
                shelves.append(("box", (0.0, yc, z), (D - 0.1, W - 0.06, 0.012), (0, 0, 0)))
                for row, x in enumerate((0.22, 0.0, -0.22)):
                    for q in range(5):
                        y = yc - W / 2 + 0.09 + q * 0.115
                        c = col if (q + sh) % 3 else col2
                        h = r.uniform(0.2, 0.26)
                        if pa.STYLE.get("cooler_mix"):                                    # kit cooler_mix: bottles with necks, short cans, milk cartons, juice boxes in bright label colours (S37 r5 CNT-02)
                            kind_ = kinds[(sh * 2 + k) % len(kinds)]
                            c = BRIGHT[(k * 3 + sh + q // 3) % len(BRIGHT)] if kind_ != "bottle" or (q + sh) % 2 else c
                            if kind_ == "can":
                                bottles.setdefault(c, []).append(("cyl", (x, y, z + 0.06 + 0.006), (0.033, 0.033, 0.12), (0, 0, 0)))
                            elif kind_ == "carton":
                                bottles.setdefault(c, []).append(("box", (x, y, z + 0.1 + 0.006), (0.075, 0.075, 0.2), (0, 0, 0)))
                            elif kind_ == "juice":
                                bottles.setdefault(c, []).append(("box", (x, y, z + 0.07 + 0.006), (0.06, 0.1, 0.14), (0, 0, 0)))
                            else:
                                bottles.setdefault(c, []).append(("cyl", (x, y, z + h * 0.35 + 0.006), (0.032, 0.032, h * 0.7), (0, 0, 0)))
                                bottles.setdefault(c, []).append(("cyl", (x, y, z + h * 0.7 + (h * 0.3) / 2 + 0.006), (0.013, 0.013, h * 0.3), (0, 0, 0)))
                            continue
                        bottles.setdefault(c, []).append(("cyl", (x, y, z + h / 2 + 0.006), (0.032, 0.026, h), (0, 0, 0)))
        groups = [(white, frame), (glow, gw), (glass, gl), (chrome, ch + shelves)]
        for c, parts in bottles.items():
            groups.append((pa._flat(f"ir_cooler_drink_{int(c[0] * 100)}_{int(c[1] * 100)}_{int(c[2] * 100)}", c, 0.3), parts))
        # category signs above the doors: one board per ~2 doors, words cycling
        per = max(1, n // 4) if n >= 4 else 1; words = list(SIGN_WORDS[:4]) if n == 8 else ["dairy", "snacks", "beverage"]
        sw = L / len(words)
        for k, wd in enumerate(words):
            groups.append((_sign_mat(wd) if not pa.STYLE.get("header_flat") else pa._flat("ir_cooler_band", tuple(pa.STYLE.get("accent_rgb") or (0.98, 0.78, 0.04)), 0.5), [("box", (D / 2 - 0.05, -L / 2 + (k + 0.5) * sw, H + 0.22), (0.03, sw - 0.06, 0.34), (0, 0, 0))]))
        return pa._prims(f"CoolerWallFactory({i}).spawn_asset({i})", groups)


class PegboardEndcapFactory:
    def __init__(self, seed):
        self.r = random.Random(seed)

    def spawn_asset(self, i):
        r = self.r
        gb_ = pa.STYLE.get("gondola_body_rgb")                              # kit gondola_body_rgb: the endcap board takes the gondola body colour (S37 r2: tall white boards beside black gondolas)
        white = pa._flat("ir_peg_white", (0.9, 0.9, 0.88), 0.4, 0.2) if not gb_ else pa._flat(f"ir_peg_body_{int(gb_[0] * 100)}", tuple(gb_), 0.4, 0.3); hook = pa._flat("ir_peg_hook", (0.6, 0.6, 0.62), 0.3, 0.9)
        D, W, H = 0.5, 0.9, 1.7
        if pa.STYLE.get("endcap_open"):                                     # kit endcap_open (S37 r11 ref: open end displays, stock facing the aisle, yellow header, no tall solid side slabs)
            return self._open(i, white, D, W, H)
        parts = [("box", (-D / 2 + 0.02, 0, H / 2), (0.03, W, H), (0, 0, 0)), ("box", (0, 0, 0.06), (D, W, 0.12), (0, 0, 0)), ("box", (0, W / 2 - 0.01, H / 2), (D, 0.02, H), (0, 0, 0)), ("box", (0, -W / 2 + 0.01, H / 2), (D, 0.02, H), (0, 0, 0))]
        hooks, cards = [], {}
        for row in range(5):
            z = 0.28 + row * 0.27
            for q in range(5):
                y = -W / 2 + 0.1 + q * 0.17
                hooks.append(("cyl", (-D / 2 + 0.08, y, z + 0.1), (0.003, 0.003, 0.14), (0, 1.57, 0)))
                c = r.choice(((0.9, 0.2, 0.2), (0.15, 0.4, 0.85), (0.95, 0.75, 0.15), (0.2, 0.65, 0.4), (0.85, 0.85, 0.85), (0.9, 0.4, 0.7)))
                cards.setdefault(c, []).append(("box", (-D / 2 + 0.14, y, z), (0.03, 0.13, 0.2), (0, 0, 0)))
                cards.setdefault((0.95, 0.95, 0.95), []).append(("box", (-D / 2 + 0.165, y, z - 0.03), (0.01, 0.1, 0.11), (0, 0, 0)))
        groups = [(white, parts), (hook, hooks)] + [(pa._flat(f"ir_peg_card_{int(c[0] * 100)}_{int(c[1] * 100)}_{int(c[2] * 100)}", c, 0.5), ps) for c, ps in cards.items()]
        return pa._prims(f"PegboardEndcapFactory({i}).spawn_asset({i})", groups)


    def _open(self, i, body, D, W, H):
        """Open end display: thin back panel, low side cheeks (to 1.1 m), 4 shelves stocked with front-facing packs, a yellow header board on the aisle (+x) face."""
        r = self.r; steel = pa._flat("ir_peg_shelf", (0.75, 0.75, 0.77), 0.35, 1.0)
        y_ = pa._flat("ir_conv_yellow_hdr", tuple(pa.STYLE.get("accent_rgb") or (0.98, 0.78, 0.04)), 0.45)
        parts = [("box", (-D / 2 + 0.015, 0, H / 2), (0.03, W, H), (0, 0, 0)), ("box", (0, 0, 0.06), (D, W, 0.12), (0, 0, 0))]
        parts += [("box", (0, s_ * (W / 2 - 0.01), 0.55), (D, 0.02, 1.1), (0, 0, 0)) for s_ in (-1, 1)]
        shelves, packs = [], {}
        pal = ((0.85, 0.15, 0.12), (0.12, 0.35, 0.8), (0.95, 0.7, 0.1), (0.15, 0.55, 0.3), (0.95, 0.95, 0.92), (0.55, 0.2, 0.55), (0.9, 0.45, 0.1), (0.1, 0.1, 0.12))
        for k, z in enumerate((0.12, 0.5, 0.88, 1.26)):
            shelves.append(("box", (0.0, 0, z + 0.01), (D - 0.06, W - 0.04, 0.02), (0, 0, 0)))
            y = -W / 2 + 0.04; c = r.choice(pal); hgt = r.uniform(0.16, 0.3); wd = r.uniform(0.07, 0.14); dep = r.uniform(0.08, 0.16); n = 0
            while y + wd < W / 2 - 0.04 and pa.STYLE.get("endcap_open") != "lib":     # "lib": bare shelves, realize stocks them from object_library_v2
                if n and n % r.randint(3, 6) == 0:
                    c = r.choice(pal); hgt = r.uniform(0.16, 0.3); wd = r.uniform(0.07, 0.14); dep = r.uniform(0.08, 0.16)
                for row in range(2):                                         # two deep
                    x = D / 2 - 0.05 - dep / 2 - row * (dep + 0.01)
                    packs.setdefault(c, []).append(("box", (x, y + wd / 2, z + 0.02 + hgt / 2), (dep, wd, hgt), (0, 0, 0)))
                    packs.setdefault((0.97, 0.97, 0.95), []).append(("box", (x + dep / 2 + 0.002, y + wd / 2, z + 0.02 + hgt * 0.45), (0.004, wd * 0.7, hgt * 0.3), (0, 0, 0)))   # a pale label panel on the face
                y += wd + 0.006; n += 1
        hdr = [("box", (D / 2 + 0.01, 0, H - 0.05), (0.02, W, 0.25), (0, 0, 0))]
        groups = [(body, parts), (steel, shelves), (y_, hdr)] + [(pa._flat(f"ir_endpack_{int(c[0] * 100)}_{int(c[1] * 100)}_{int(c[2] * 100)}", c, 0.45), ps) for c, ps in packs.items()]
        return pa._prims(f"PegboardEndcapFactory({i}).spawn_asset({i})", groups)


class CategorySignFactory:
    def __init__(self, seed):
        self.word = SIGN_WORDS[random.Random(seed).randrange(len(SIGN_WORDS))]

    def spawn_asset(self, i):
        frame = pa._flat("ir_catsign_frame", (0.85, 0.85, 0.85), 0.5)
        return pa._prims(f"CategorySignFactory({i}).spawn_asset({i})", [(frame, [("box", (0.0, 0, 0.15), (0.035, 1.22, 0.32), (0, 0, 0))]), (_sign_mat(self.word), [("box", (0.02, 0, 0.15), (0.01, 1.2, 0.3), (0, 0, 0))])])
